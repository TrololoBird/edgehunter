"""Atomic file replacement with durable writes and Windows sharing retries."""
import os
import tempfile
import time

REPLACE_ATTEMPTS = 10
REPLACE_WAIT_SEC = 0.05
REPLACE_WAIT_MAX_SEC = 1.0


def atomic_write(path: str, data: bytes):
    """Flush a unique sibling tempfile, replace the target, then sync its POSIX directory.

    Concurrent writers publish complete files; the last successful replacement wins.
    A directory-sync failure is reported even though replacement may already have succeeded.
    """
    target = os.path.abspath(os.fspath(path))
    directory = os.path.dirname(target)
    fd, tmp = tempfile.mkstemp(prefix='.' + os.path.basename(target) + '.', suffix='.tmp', dir=directory)
    try:
        with os.fdopen(fd, 'wb') as fh:
            try:
                os.chmod(tmp, os.stat(target).st_mode & 0o777)
            except FileNotFoundError:
                pass
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        for attempt in range(REPLACE_ATTEMPTS):
            try:
                os.replace(tmp, target)
                break
            except PermissionError:
                if attempt == REPLACE_ATTEMPTS - 1:
                    raise
                time.sleep(min(REPLACE_WAIT_SEC * 2 ** attempt, REPLACE_WAIT_MAX_SEC))
        if os.name == 'posix':
            dir_fd = os.open(directory, os.O_RDONLY | getattr(os, 'O_DIRECTORY', 0))
            try:
                os.fsync(dir_fd)
            finally:
                os.close(dir_fd)
    finally:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass


def append_jsonl(path: str, rows) -> None:
    """Append complete JSONL records with one flush/fsync per batch.

    Runtime JSONL files are sometimes inspected or generated by a root-owned
    maintenance job.  The service user owns the data directory, so it can
    replace such a file but cannot open it for append.  In that case publish
    one atomic copy containing the old records and this batch; the next write
    is then owned by the service user again.
    """
    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, exist_ok=True)
    batch = ''.join(row if row.endswith('\n') else row + '\n' for row in rows)
    try:
        fh = open(path, 'a', encoding='utf-8')
    except PermissionError:
        # The directory owner may replace a file owned by another user.  Read
        # before replacing so a root-created history is retained in full.
        with open(path, encoding='utf-8') as old:
            previous = old.read()
        atomic_write(path, (previous + batch).encode('utf-8'))
        return
    with fh:
        fh.write(batch)
        fh.flush()
        os.fsync(fh.fileno())
